import assert from 'node:assert/strict';
import {TrainingEngine, replay, type TrainingEvent} from '../../studio/core/training';
import {deriveInputRateTimeline} from '../../studio/core/input-rate-timeline';
import {exportStudioSession} from '../../studio/core/session-export';
const e=new TrainingEngine({sessionId:'long-record-controlled',inputObservation:{runId:'long-run'},clock:{now:()=>0,wallTime:()=>new Date(1700000000000).toISOString(),id:(()=>{let i=0;return()=>`seed-${++i}`})()}});
e.beginComposition();
const seed=e.getSnapshot(),last=seed.events.at(-1)!;
const count=Number(process.env.LONG_RECORD_COUNT??16000);
const events:TrainingEvent[]=[...seed.events];
for(let i=1;i<=count;i++)events.push({...last,type:'inputObservationSampled',eventId:`long-${i}`,sequence:last.sequence+i,wallTime:new Date(1700000000000+i*1000).toISOString(),inputObservation:{...last.inputObservation!,atMs:i*1000,restartReason:null}});
const snapshot=replay(events);console.log('LEGAL_REPLAY',snapshot.events.length);
const timeline=deriveInputRateTimeline(snapshot);assert.equal(timeline.points.length,count+1); console.log('TIMELINE',timeline.points.length);
const result=exportStudioSession(snapshot,'2026-10-09T00:00:00.000Z');
assert.equal(JSON.parse(result.json).rawEvents.length,events.length);
assert.equal(JSON.parse(result.json).inputRateTimeline.points.length,count+1);
assert.equal(result.csv.split('\r\n').filter(row=>row.startsWith('"event",')).length,events.length);
assert.equal(result.csv.split('\r\n').filter(row=>row.startsWith('"input_rate_point",')).length,count+1);
console.log('EXPORT_COMPLETE',result.json.length,result.csv.length);
const {readLegacyHistoryRecord}=await import('../../studio/core/legacy-history');
const {projectLegacyHistoryHud}=await import('../../studio/core/legacy-history-hud');
const projected=projectLegacyHistoryHud(readLegacyHistoryRecord({sessionId:snapshot.sessionId,sequence:snapshot.sequence,updatedAt:'2026-10-09T00:00:00.000Z',snapshot}));
assert.ok(projected.timeline);assert.equal(projected.timeline.points.length,count+1);
assert.equal(projected.trends.reduce((sum,window)=>sum+window.metric.points.length,0),count+1);
console.log('HUD_COMPLETE',projected.trends.length,'windows');
