import test from 'node:test';
import assert from 'node:assert/strict';
import {
  CAFE_MATERIAL, PACE_RULE_VERSION, RULE_VERSION, SCHEMA_VERSION, TrainingEngine,
  align, exportSession, getCurrentResult, getDraft, hasScorableReference, reduceTraining,
  replay, tokens, validateSnapshot,
  type Attempt, type EventPayload, type Material, type TrainingEvent, type TrainingSnapshot,
} from './training.ts';
import { getDraftFeedback } from './draft-feedback.ts';

function fixture(reference: string) {
  let serial = 0;
  const clock = { now: () => 0, wallTime: () => '2026-10-07T00:00:00.000Z', id: () => `zero-reference-${++serial}` };
  const material: Material = { id: 'reference-guard', version: 'v1', title: 'Reference guard', rights: 'Original test fixture', cues: [
    { id: 'target', text: reference, start: 0, end: 6 }, { id: 'valid', text: 'one two three', start: 6, end: 12 },
  ] };
  const engine = new TrainingEngine({ material, clock });
  function event(payload: EventPayload, snapshot = engine.getSnapshot()): TrainingEvent {
    return { ...payload, eventId: clock.id(), sessionId: snapshot.sessionId, sequence: snapshot.sequence + 1,
      wallTime: clock.wallTime(), activeMs: snapshot.activeMs, cueId: snapshot.material.cues[snapshot.cueIndex].id,
      inputVersion: getDraft(snapshot).version, schemaVersion: SCHEMA_VERSION, ruleVersion: RULE_VERSION,
      paceRuleVersion: PACE_RULE_VERSION, materialId: material.id, materialVersion: material.version };
  }
  return { engine, event, clock };
}

for (const [name, reference] of [['empty', ''], ['whitespace', ' \t\n '], ['punctuation', '...!?—'], ['Chinese', '你好世界'], ['Arabic', 'مرحبا']] as const) {
  test(`${name} references remain ungraded through submit, direct events and export`, () => {
    assert.equal(hasScorableReference(reference), false);
    for (const answer of ['hello', '!!!', '你好']) {
      const { engine, event } = fixture(reference);
      engine.input(answer);
      const before = engine.getSnapshot();
      assert.equal(engine.submit(), null);
      assert.equal(engine.submit(), null);
      assert.equal(engine.getSnapshot(), before, 'No submission or judgment events are generated');
      assert.equal(align(reference, answer).words, 0);
      assert.equal(align(reference, answer).accuracy, 0);
      engine.dispatch(event({ type: 'submitRequested', attemptId: 'direct', answer, draftVersion: getDraft(before).version }));
      assert.deepEqual(engine.getSnapshot().pendingAttempts, {});
      assert.equal(engine.getSnapshot().frozenReasons.includes('checking'), false);
      engine.dispatch(event({ type: 'judgmentApplied', attemptId: 'direct' }));
      const snapshot = engine.getSnapshot();
      assert.equal(snapshot.attempts.length, 0);
      assert.equal(snapshot.earnedWords, 0);
      assert.deepEqual(snapshot.completedCueIds, []);
      assert.equal(engine.currentResult, null);
      assert.equal(getDraftFeedback(snapshot, answer).status, 'unjudged');
      const exported = exportSession(snapshot, '2026-10-07T00:00:00.000Z');
      assert.deepEqual(exported.snapshot.attempts, []);
      assert.deepEqual(exported.snapshot.conditions, []);
      assert.deepEqual(exported.snapshot.curves, []);
      assert.ok(!exported.csv.split('\r\n').some(row => /^"(?:attempt|conditions|curve_point)",/.test(row)));
      assert.deepEqual(JSON.parse(exported.json).rawEvents, snapshot.events);
      assert.deepEqual(replay(snapshot.events), snapshot);
    }
  });
}

/** Reproduce the serialized shape generated by v19, before reference guards existed. */
function legacySnapshots() {
  const { engine, event, clock } = fixture('...');
  engine.exposeHint('hint'); engine.input('!!!', 'paste');
  const before = engine.getSnapshot(), draft = getDraft(before), attemptId = 'legacy-zero-words';
  const conditions = { exposure: 'first' as const, hinted: true, revealed: false, pasted: true, inputSource: 'paste' as const };
  const submission = event({ type: 'submitRequested', attemptId, answer: draft.text, draftVersion: draft.version }, before);
  const pending: TrainingSnapshot = { ...before, sequence: submission.sequence, events: [...before.events, submission],
    frozenReasons: ['checking'], pendingAttempts: { [attemptId]: { attemptId, cueId: engine.cue.id, answer: draft.text, inputVersion: draft.version, conditions } } };
  const judgment = event({ type: 'judgmentApplied', attemptId }, pending);
  const attempt: Attempt = { ...align(engine.cue.text, draft.text), accuracy: 100, attemptId, sessionId: before.sessionId,
    roundId: before.roundId, cueId: engine.cue.id, materialId: before.material.id, materialVersion: before.material.version,
    ruleVersion: RULE_VERSION, reference: engine.cue.text, answer: draft.text, inputVersion: draft.version, conditions,
    gain: 0, firstCompletion: false, activeMs: before.activeMs, wallTime: judgment.wallTime, dataset: 'local_interactive' };
  const reviewed: TrainingSnapshot = { ...pending, sequence: judgment.sequence, events: [...pending.events, judgment],
    pendingAttempts: {}, frozenReasons: ['review'], attempts: [attempt] };
  return { pending, reviewed, judgment, clock, event };
}

test('legacy pending judgments are discarded and release only their checking freeze', () => {
  const { pending, judgment, event } = legacySnapshots();
  const result = reduceTraining(pending, judgment);
  assert.deepEqual(result.pendingAttempts, {});
  assert.equal(result.frozenReasons.includes('checking'), false);
  assert.equal(result.frozenReasons.includes('review'), false);
  assert.deepEqual(result.discardedJudgmentIds, ['legacy-zero-words']);
  assert.deepEqual(result.attempts, []);
  const twoPending: TrainingSnapshot = { ...pending, frozenReasons: ['checking', 'paused'], pendingAttempts: {
    ...pending.pendingAttempts, second: { ...pending.pendingAttempts['legacy-zero-words'], attemptId: 'second' },
  } };
  const oneRemaining = reduceTraining(twoPending, judgment);
  assert.deepEqual(oneRemaining.frozenReasons, ['checking', 'paused']);
  assert.deepEqual(Object.keys(oneRemaining.pendingAttempts), ['second']);
  const cleared = reduceTraining(oneRemaining, event({ type: 'judgmentApplied', attemptId: 'second' }, oneRemaining));
  assert.deepEqual(cleared.frozenReasons, ['paused']);
  assert.deepEqual(cleared.attempts, []);
});

test('v19 pending and completed zero-word event logs restore without fake attempts or lost raw events', () => {
  const { pending, reviewed, clock } = legacySnapshots();
  for (const legacy of [pending, reviewed]) {
    const restored = new TrainingEngine({ snapshot: structuredClone(legacy), clock });
    const state = restored.getSnapshot();
    assert.deepEqual(state.events, legacy.events);
    assert.equal(state.sequence, legacy.sequence);
    assert.equal(state.activeMs, legacy.activeMs);
    assert.deepEqual(state.attempts, []);
    assert.deepEqual(state.pendingAttempts, {});
    assert.equal(state.frozenReasons.includes('checking'), false);
    assert.equal(restored.currentResult, null);
    assert.equal(restored.submit(), null);
    assert.equal(getDraftFeedback(state, restored.draft).status, 'unjudged');
    assert.deepEqual(validateSnapshot(structuredClone(legacy)).attempts, []);
    assert.deepEqual(exportSession(state).snapshot.curves, []);
    restored.nextCue(1); restored.input('one two three');
    const firstValidAttempt = restored.submit()!;
    assert.equal(firstValidAttempt.conditions.exposure, 'first');
    assert.equal(firstValidAttempt.gain, 3);
    assert.equal(firstValidAttempt.firstCompletion, true);
    assert.deepEqual(replay(restored.getSnapshot().events), restored.getSnapshot());
  }
});

test('a foreign or legacy zero-word result cannot become current matched feedback', () => {
  const { reviewed } = legacySnapshots();
  assert.equal(getCurrentResult(reviewed), null);
  const feedback = getDraftFeedback(reviewed, '!!!');
  assert.equal(feedback.status, 'unjudged');
  assert.equal(feedback.attempt, null);
  assert.doesNotMatch(feedback.message, /本句已匹配/);
});

test('existing English normalization and nonempty-reference first/retry rewards remain unchanged', () => {
  assert.ok(CAFE_MATERIAL.cues.every(cue => hasScorableReference(cue.text)));
  assert.deepEqual(tokens('ＩＴ’s A COFFEE １２.'), ["it's", 'a', 'coffee', '12']);
  assert.equal(hasScorableReference('１２'), true);
  assert.equal(align("It's coffee", 'ＩＴ’S COFFEE!').accuracy, 100);
  const { engine } = fixture('one two three');
  engine.exposeHint('hint'); engine.input('!!!', 'paste');
  const missing = engine.submit()!;
  assert.equal(missing.words, 3); assert.equal(missing.errors, 3); assert.equal(missing.accuracy, 0);
  assert.equal(missing.conditions.exposure, 'first');
  engine.input('one wrong three'); assert.equal(engine.submit()?.gain, 2);
  engine.exposeHint('reveal'); engine.input('one two three extra');
  const extra = engine.submit()!;
  assert.equal(extra.gain, 1); assert.equal(extra.firstCompletion, false);
  assert.equal(engine.getSnapshot().completedCueIds.length, 0);
  engine.input('one two three'); const complete = engine.submit()!;
  assert.equal(complete.gain, 0); assert.equal(complete.firstCompletion, true);
  assert.deepEqual(complete.conditions, { exposure: 'retry', hinted: true, revealed: true, pasted: true, inputSource: 'typed' });
  assert.equal(engine.submit(), complete);
  const snapshot = engine.getSnapshot();
  assert.equal(snapshot.attempts.length, 4); assert.equal(snapshot.earnedWords, 3);
  assert.deepEqual(replay(snapshot.events), snapshot);
  const exported = exportSession(snapshot);
  assert.equal(exported.snapshot.conditions.length, 4); assert.equal(exported.snapshot.curves.length, 4);
  assert.deepEqual(JSON.parse(exported.json).attempts, snapshot.attempts);
});
